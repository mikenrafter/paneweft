// The byte budget of one reply and the bounded forms used when a reply would exceed it (review S3).
//
// Reason: the pager bounds paged listings, but failure bodies (a message that echoes caller input, one issue per fault) and replies that do not
// page were unbounded. Every exit of an operation goes through `enforceReplyBudget` (operations.ts) or `boundError` (CLI exits that print an
// error without an operation), so the budget holds once, at the exit, instead of in each producer.
// CLAIM(bounded-exit): a reply body is never longer than its budget in UTF-8 bytes, is never cut inside a code point, and a reply that was cut
//   says so: `details.truncated` on errors, `schemaVersion: "paneweft.truncated/1"` on successes [operations.exit-budget.test.ts; design section 4].
// Budget rule: `maxBytes` when it is an integer in range (default 8192, capped at 32768); below the 2048 floor the floor applies, because
//   BUDGET_TOO_SMALL must still be answerable and that answer is itself bounded to the floor.
// Errors keep their code and retryability. Messages are clipped to MESSAGE_BYTES, issue fields to ISSUE_FIELD_BYTES, `details` is dropped when large,
// and as many issues as fit are kept IN ORDER. `details.truncated` = {budgetBytes, messageBytesOmitted, errorsTotal, errorsOmitted,
// issueFieldsClipped, detailsOmitted?, continuation}. Nothing is stored for continuation: an error list is regenerated by fixing the reported
// issues and calling again, which the `continuation` text says.
import type { OperationError, ValidationIssue } from "./errors.ts";

export const DEFAULT_REPLY_BYTES = 8192;
export const MINIMUM_REPLY_BYTES = 2048;
export const MAXIMUM_REPLY_BYTES = 32768;
const MESSAGE_BYTES = 400;
const ISSUE_FIELD_BYTES = 240;
const DETAILS_BYTES = 400;

export const byteLength = (text: string): number => Buffer.byteLength(text, "utf8");

/** The byte budget a request asks for (see the budget rule above). */
export function replyBudget(maxBytes: unknown): number {
  if (typeof maxBytes !== "number" || !Number.isInteger(maxBytes)) return DEFAULT_REPLY_BYTES;
  return Math.min(MAXIMUM_REPLY_BYTES, Math.max(MINIMUM_REPLY_BYTES, maxBytes));
}

/** The longest prefix of `text` of at most `maxBytes` UTF-8 bytes that ends on a code point boundary. */
export function prefixWithin(text: string, maxBytes: number): string {
  if (byteLength(text) <= maxBytes) return text;
  const bytes = Buffer.from(text, "utf8");
  let end = Math.max(0, maxBytes);
  while (end > 0 && ((bytes[end] as number) & 0xc0) === 0x80) end -= 1;
  return bytes.subarray(0, end).toString("utf8");
}

/** `text` cut to at most `maxBytes` bytes including a trailing "…" when it was cut; `omittedBytes` counts the original bytes dropped. */
function clip(text: string, maxBytes: number): { text: string; omittedBytes: number } {
  if (byteLength(text) <= maxBytes) return { text, omittedBytes: 0 };
  const kept = prefixWithin(text, Math.max(0, maxBytes - 3));
  return { text: `${kept}…`, omittedBytes: byteLength(text) - byteLength(kept) };
}

const issueOf = (issue: ValidationIssue, clipped: { count: number }): ValidationIssue => {
  const field = (value: string): string => {
    const cut = clip(value, ISSUE_FIELD_BYTES);
    if (cut.omittedBytes > 0) clipped.count += 1;
    return cut.text;
  };
  return { code: issue.code, pointer: field(issue.pointer), constraint: field(issue.constraint), hint: field(issue.hint) };
};

/** The error itself when it fits `budget`, else a bounded copy that states what was left out. */
export function boundError(error: OperationError, budget: number): OperationError {
  if (byteLength(JSON.stringify(error)) <= budget) return error;
  const total = error.errors.length;
  const detailsOmitted = error.details !== undefined && byteLength(JSON.stringify(error.details)) > DETAILS_BYTES;
  const build = (messageLimit: number, kept: number): OperationError => {
    const message = clip(error.message, messageLimit);
    const clipped = { count: 0 };
    const errors = error.errors.slice(0, kept).map((issue) => issueOf(issue, clipped));
    const continuation = total > kept
      ? `${total - kept} of ${total} issues are not listed; fix the listed issues and call again to see the next ones`
      : "the message was shortened; the code and the listed issues are complete";
    return {
      schemaVersion: error.schemaVersion,
      code: error.code,
      message: message.text,
      errors,
      retryable: error.retryable,
      details: {
        ...(error.details === undefined || detailsOmitted ? {} : error.details),
        truncated: {
          budgetBytes: budget, messageBytesOmitted: message.omittedBytes, errorsTotal: total, errorsOmitted: total - kept,
          issueFieldsClipped: clipped.count, ...(detailsOmitted ? { detailsOmitted: true } : {}), continuation,
        },
      },
    };
  };
  const fits = (candidate: OperationError): boolean => byteLength(JSON.stringify(candidate)) <= budget;
  for (let messageLimit = MESSAGE_BYTES; ; messageLimit = Math.floor(messageLimit / 2)) {
    // the largest number of issues that fits is found by bisection (size grows with the count)
    let low = 0;
    let high = total;
    while (low < high) {
      const middle = Math.ceil((low + high) / 2);
      if (fits(build(messageLimit, middle))) low = middle;
      else high = middle - 1;
    }
    const candidate = build(messageLimit, low);
    if (fits(candidate) || messageLimit <= 16) return candidate;
  }
}

/** The bounded replacement of a SUCCESSFUL reply that exceeded `budget`; the operation already happened and is not repeated. */
export function boundSuccessBody(body: string, format: "text" | "json", operation: string, budget: number): { body: string; payload: Record<string, unknown> } {
  const total = byteLength(body);
  const continuation = "the operation completed and is not repeated; request the same read again with a larger maxBytes or a cursor if it pages";
  const build = (keptBytes: number): { body: string; payload: Record<string, unknown> } => {
    const excerpt = prefixWithin(body, keptBytes);
    const omittedBytes = total - byteLength(excerpt);
    const payload = { schemaVersion: "paneweft.truncated/1", operation, complete: false, totalBytes: total, omittedBytes, excerpt, continuation };
    return {
      body: format === "json" ? JSON.stringify(payload) : `${excerpt}\n[truncated: ${omittedBytes} of ${total} bytes omitted; ${continuation}]\n`,
      payload,
    };
  };
  let low = 0;
  let high = total;
  while (low < high) {
    const middle = Math.ceil((low + high) / 2);
    if (byteLength(build(middle).body) <= budget) low = middle;
    else high = middle - 1;
  }
  return build(low);
}
