// Build tooling only. Generates packages/paneweft-ts/types/*.d.ts, the declarations a consumer's compiler reads for @paneweft/sdk (F4). The package ships its
// TypeScript sources (they run under tsx and Vitest) whose imports end in `.ts`; a consumer's `tsc` reading those sources fails with TS5097 unless it enables
// allowImportingTsExtensions, and would also typecheck them under the consumer's own strictness. The `types` condition of the package exports points at these files
// instead. `--check` exits 1 with STALE_TYPES <file> when the committed declarations differ from what the sources produce.
import { spawnSync } from "node:child_process";
import { cpSync, existsSync, mkdirSync, mkdtempSync, readdirSync, readFileSync, rmSync, writeFileSync } from "node:fs";
import { tmpdir } from "node:os";
import { join, relative, resolve } from "node:path";
import { fileURLToPath } from "node:url";

const root = resolve(fileURLToPath(new URL("..", import.meta.url)));
const packageDir = join(root, "packages/paneweft-ts");
const outputDir = join(packageDir, "types");
const tsc = join(root, "node_modules/typescript/lib/tsc.js");
const MARKER = "GENERATED.txt";

const scratch = mkdtempSync(join(tmpdir(), "paneweft-sdk-types-"));
try {
  const run = spawnSync(process.execPath, [tsc, "-p", join(packageDir, "tsconfig.types.json"), "--outDir", scratch], { cwd: packageDir, encoding: "utf8" });
  if (run.status !== 0) { process.stderr.write(`${run.stdout}${run.stderr}`); process.exit(1); }
  // TypeScript keeps the `.ts` of a relative specifier in declaration output; a consumer that does not skip library checks would report TS5097 in every
  // declaration file, so the specifiers are written as the `.js` that NodeNext and bundler resolution map back to the `.d.ts` beside them.
  for (const name of readdirSync(scratch, { recursive: true })) {
    if (!String(name).endsWith(".d.ts")) continue;
    const path = join(scratch, String(name));
    const text = readFileSync(path, "utf8");
    writeFileSync(path, text.replace(/(\bfrom\s+|\bimport\(\s*|\bimport\s+)(["'])(\.{1,2}\/[^"']*?)\.ts\2/g, "$1$2$3.js$2"));
  }
  writeFileSync(join(scratch, MARKER), "Generated by `npm run gen:types:sdk` from ../src with the repository's TypeScript. Do not edit.\n");
  const listing = (directory) => (existsSync(directory) ? readdirSync(directory, { recursive: true, withFileTypes: true }).filter((entry) => entry.isFile()).map((entry) => relative(directory, join(entry.parentPath, entry.name))).sort() : []);
  if (process.argv.includes("--check")) {
    const fresh = listing(scratch);
    const committed = listing(outputDir);
    let stale = false;
    for (const name of new Set([...fresh, ...committed])) {
      const left = existsSync(join(outputDir, name)) ? readFileSync(join(outputDir, name), "utf8") : null;
      const right = existsSync(join(scratch, name)) ? readFileSync(join(scratch, name), "utf8") : null;
      if (left !== right) { console.error(`STALE_TYPES ${name}`); stale = true; }
    }
    process.exit(stale ? 1 : 0);
  }
  rmSync(outputDir, { recursive: true, force: true });
  mkdirSync(outputDir, { recursive: true });
  cpSync(scratch, outputDir, { recursive: true });
} finally {
  rmSync(scratch, { recursive: true, force: true });
}
