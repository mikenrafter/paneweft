// Build tooling only. json-schema-to-typescript is exactly pinned in package.json/package-lock.json.
// Resolve local URNs without network access. The envelope's conditional component/data mapping
// is projected to a TypeScript discriminated union from the canonical schema's own if/then clauses.
import { compile } from "json-schema-to-typescript";
import { readFile, readdir, mkdir, writeFile } from "node:fs/promises";
import { resolve, join } from "node:path";
import { fileURLToPath } from "node:url";

const root = resolve(fileURLToPath(new URL("..", import.meta.url)));
const arg = (name, fallback) => { const at = process.argv.indexOf(name); return at < 0 ? fallback : resolve(process.argv[at + 1]); };
const schemaDir = arg("--schemas", join(root, "src/schemas"));
const outputDir = arg("--out", join(root, "src/generated"));
const schemas = new Map();
async function collect(dir) {
  for (const entry of (await readdir(dir, { withFileTypes: true })).sort((a, b) => a.name.localeCompare(b.name, "en"))) {
    const path = join(dir, entry.name);
    if (entry.isDirectory()) await collect(path);
    else if (entry.name.endsWith(".schema.json")) {
      const schema = JSON.parse(await readFile(path, "utf8")); schemas.set(schema.$id, schema);
    }
  }
}
await collect(schemaDir);
function inline(node, document) {
  if (Array.isArray(node)) return node.map((entry) => inline(entry, document));
  if (!node || typeof node !== "object") return node;
  if (node.$ref) {
    const [id, fragment] = node.$ref.split("#");
    const targetDoc = id ? schemas.get(id) : document;
    if (!targetDoc) throw new Error(`Unregistered schema ${id}`);
    let target = targetDoc;
    for (const key of (fragment ?? "").split("/").slice(1)) target = target[key.replace(/~1/g, "/").replace(/~0/g, "~")];
    return inline(target, targetDoc);
  }
  return Object.fromEntries(Object.entries(node).filter(([key]) => !["$id", "$schema", "$defs", "x-hint"].includes(key)).map(([key, value]) => [key, inline(value, document)]));
}
const bannerComment = "/* Generated by npm run gen:types using json-schema-to-typescript 16.0.0. Do not edit. */";
const outputs = new Map();
async function emit(name, schema, document) {
  const expanded = inline(schema, document); delete expanded.title;
  outputs.set(`${name}.ts`, await compile(expanded, name, { bannerComment, additionalProperties: false, maxItems: 0, unknownAny: true }));
}
const envelope = schemas.get("urn:paneweft:schema:envelope:1");
const metadata = structuredClone(envelope);
delete metadata.allOf;
for (const key of ["component", "completeness", "data"]) delete metadata.properties[key];
metadata.required = metadata.required.filter((key) => !["component", "completeness", "data"].includes(key));
await emit("EnvelopeMetadata", metadata, envelope);
const common = schemas.get("urn:paneweft:schema:common:1");
const completenessNames = [];
for (const rule of common.$defs.Completeness.allOf) {
  const status = rule.if.properties.status.const;
  const name = `${status[0].toUpperCase()}${status.slice(1)}Completeness`;
  completenessNames.push([status, name]);
  const variant = structuredClone(common.$defs.Completeness);
  delete variant.allOf;
  variant.properties = { ...variant.properties, ...rule.then.properties, status: { const: status } };
  variant.required = [...variant.required, ...rule.then.required];
  await emit(name, variant, common);
}
const components = [];
for (const rule of envelope.allOf) {
  const component = rule.if?.properties?.component?.const;
  if (!component) continue;
  const name = `${component[0].toUpperCase()}${component.slice(1)}Data`;
  components.push([component, name]);
  await emit(name, rule.then.properties.data, envelope);
}
let index = `${bannerComment}\nimport type { EnvelopeMetadata } from "./EnvelopeMetadata.ts";\n`;
for (const [, name] of [...components, ...completenessNames]) index += `import type { ${name} } from "./${name}.ts";\n`;
index += "export type SupportedEnvelope =\n" + components.map(([id, name]) => `  | (EnvelopeMetadata & { component: ${JSON.stringify(id)}; completeness: CompleteCompleteness | PartialCompleteness; data: ${name} })`).join("\n") + ";\n";
index += `export type UnsupportedEnvelope = EnvelopeMetadata & { component: ${components.map(([id]) => JSON.stringify(id)).join(" | ")}; completeness: UnsupportedCompleteness; data?: never };\nexport type Envelope = SupportedEnvelope | UnsupportedEnvelope;\n`;
outputs.set("index.ts", index);
if (process.argv.includes("--check")) {
  let stale = false;
  for (const [name, content] of outputs) {
    const actual = await readFile(join(outputDir, name), "utf8").catch(() => null);
    if (actual !== content) { console.error(`STALE_TYPES ${name}`); stale = true; }
  }
  if (stale) process.exitCode = 1;
} else {
  await mkdir(outputDir, { recursive: true });
  for (const [name, content] of outputs) await writeFile(join(outputDir, name), content);
}
