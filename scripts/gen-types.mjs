// Build tooling only. json-schema-to-typescript is exactly pinned in package.json/package-lock.json.
// Resolve local URNs without network access. The envelope's conditional component/data mapping
// is projected to a TypeScript discriminated union from the canonical schema's own if/then clauses.
import { compile } from "json-schema-to-typescript";
import { readFile, readdir, mkdir, writeFile } from "node:fs/promises";
import { resolve, join } from "node:path";
import { fileURLToPath } from "node:url";

const root = resolve(fileURLToPath(new URL("..", import.meta.url)));
const arg = (name, fallback) => { const at = process.argv.indexOf(name); return at < 0 ? fallback : resolve(process.argv[at + 1]); };
const schemaDir = arg("--schemas", join(root, "src/schemas"));
const outputDir = arg("--out", join(root, "src/generated"));
const schemas = new Map();
async function collect(dir) {
  for (const entry of (await readdir(dir, { withFileTypes: true })).sort((a, b) => a.name.localeCompare(b.name, "en"))) {
    const path = join(dir, entry.name);
    if (entry.isDirectory()) await collect(path);
    else if (entry.name.endsWith(".schema.json")) {
      const schema = JSON.parse(await readFile(path, "utf8")); schemas.set(schema.$id, schema);
    }
  }
}
await collect(schemaDir);
function inline(node, document) {
  if (Array.isArray(node)) return node.map((entry) => inline(entry, document));
  if (!node || typeof node !== "object") return node;
  if (node.$ref) {
    const [id, fragment] = node.$ref.split("#");
    const targetDoc = id ? schemas.get(id) : document;
    if (!targetDoc) throw new Error(`Unregistered schema ${id}`);
    let target = targetDoc;
    for (const key of (fragment ?? "").split("/").slice(1)) target = target[key.replace(/~1/g, "/").replace(/~0/g, "~")];
    return inline(target, targetDoc);
  }
  // `if {type: T} then A else B` is a union by value kind (the notebook's EvidenceTarget: a {viewId, itemId} object or a bare source id).
  if (node.if && node.then && node.else && Object.keys(node.if).every((key) => key === "type")) {
    const { if: _if, then, else: otherwise, ...rest } = node;
    return inline({ ...rest, anyOf: [then, otherwise] }, document);
  }
  return Object.fromEntries(Object.entries(node).filter(([key]) => !["$id", "$schema", "$defs", "x-hint"].includes(key)).map(([key, value]) => [key, inline(value, document)]));
}
const bannerComment = "/* Generated by npm run gen:types using json-schema-to-typescript 16.0.0. Do not edit. */";
const outputs = new Map();
async function emit(name, schema, document) {
  const expanded = inline(schema, document); delete expanded.title;
  outputs.set(`${name}.ts`, await compile(expanded, name, { bannerComment, additionalProperties: false, maxItems: 0, unknownAny: true }));
}
const envelope = schemas.get("urn:paneweft:schema:envelope:1");
const metadata = structuredClone(envelope);
delete metadata.allOf;
for (const key of ["component", "completeness", "data"]) delete metadata.properties[key];
metadata.required = metadata.required.filter((key) => !["component", "completeness", "data"].includes(key));
await emit("EnvelopeMetadata", metadata, envelope);
const common = schemas.get("urn:paneweft:schema:common:1");
const completenessNames = [];
for (const rule of common.$defs.Completeness.allOf) {
  const status = rule.if.properties.status.const;
  const name = `${status[0].toUpperCase()}${status.slice(1)}Completeness`;
  completenessNames.push([status, name]);
  const variant = structuredClone(common.$defs.Completeness);
  delete variant.allOf;
  variant.properties = { ...variant.properties, ...rule.then.properties, status: { const: status } };
  variant.required = [...variant.required, ...rule.then.required];
  await emit(name, variant, common);
}
// ---- the envelope's data rules, DERIVED from the schema's own conditionals (N4) -------------------------------------------------
// The envelope schema states them as `allOf` rules. Two shapes are understood; any other rule makes this script fail loudly
// (UNSUPPORTED_CONDITIONAL) so a rule can never be silently ignored while the committed declarations still look current.
//   status rule:    if { completeness.status const S } then/else { properties.data: false | required: ["data"] | neither }
//   component rule: if { component const C }           then { properties.data: <schema of data> }
const fail = (message) => { console.error(message); process.exit(2); };
const keysWithin = (node, allowed) => Object.keys(node).every((key) => allowed.includes(key) || key === "x-hint");
/** `{ required: [name], properties: { name: { const } } }` -> const, nested one level when `inner` is given. */
function constCondition(condition, name, inner) {
  if (!condition || !keysWithin(condition, ["type", "required", "properties"])) return undefined;
  if (JSON.stringify(condition.required) !== JSON.stringify([name])) return undefined;
  if (JSON.stringify(Object.keys(condition.properties ?? {})) !== JSON.stringify([name])) return undefined;
  let node = condition.properties[name];
  if (inner !== undefined) {
    if (!node || !keysWithin(node, ["type", "required", "properties"])) return undefined;
    if (JSON.stringify(Object.keys(node.properties ?? {})) !== JSON.stringify([inner])) return undefined;
    node = node.properties[inner];
  }
  return node && Object.keys(node).length === 1 && "const" in node ? node.const : undefined;
}
/** What a then/else branch says about `data`: "forbidden", "required" or "optional". Anything else is not understood. */
function dataMode(branch, where) {
  if (branch === undefined) return "optional";
  if (!keysWithin(branch, ["type", "required", "properties"])) fail(`UNSUPPORTED_CONDITIONAL ${where}: branch members other than required/properties`);
  const others = Object.keys(branch.properties ?? {}).filter((key) => key !== "data");
  const requiredOthers = (branch.required ?? []).filter((key) => key !== "data");
  if (others.length > 0 || requiredOthers.length > 0) fail(`UNSUPPORTED_CONDITIONAL ${where}: the branch constrains properties other than data`);
  if (branch.properties?.data === false) return "forbidden";
  if (branch.properties && "data" in branch.properties) fail(`UNSUPPORTED_CONDITIONAL ${where}: data may only be forbidden here`);
  return (branch.required ?? []).includes("data") ? "required" : "optional";
}
const completenessStatuses = completenessNames.map(([status]) => status);
const statusRules = [];
const components = [];
for (const [position, rule] of envelope.allOf.entries()) {
  const where = `envelope.allOf[${position}]`;
  const status = constCondition(rule.if, "completeness", "status");
  const component = constCondition(rule.if, "component");
  if (status !== undefined && keysWithin(rule, ["if", "then", "else"])) {
    if (!completenessStatuses.includes(status)) fail(`UNSUPPORTED_CONDITIONAL ${where}: unknown completeness status ${JSON.stringify(status)}`);
    statusRules.push({ status, then: dataMode(rule.then, `${where}.then`), else: dataMode(rule.else, `${where}.else`) });
  } else if (component !== undefined && keysWithin(rule, ["if", "then"]) && rule.then?.properties?.data) {
    if (Object.keys(rule.then.properties).length !== 1) fail(`UNSUPPORTED_CONDITIONAL ${where}: a component rule may only set data`);
    const name = `${component[0].toUpperCase()}${component.slice(1)}Data`;
    components.push([component, name]);
    await emit(name, rule.then.properties.data, envelope);
  } else {
    fail(`UNSUPPORTED_CONDITIONAL ${where}: this rule is neither a completeness-status rule nor a component rule`);
  }
}
if (statusRules.length !== 1) fail(`UNSUPPORTED_CONDITIONAL envelope.allOf: expected exactly one completeness-status rule, found ${statusRules.length}`);
const [statusRule] = statusRules;
/** data mode per completeness variant: rule.then when the status matches, rule.else otherwise. */
const modeOf = (status) => (status === statusRule.status ? statusRule.then : statusRule.else);
const statusesByMode = new Map();
for (const status of completenessStatuses) statusesByMode.set(modeOf(status), [...(statusesByMode.get(modeOf(status)) ?? []), status]);
const nameOfStatus = Object.fromEntries(completenessNames);
const unionNames = { required: "SupportedEnvelope", optional: "LenientEnvelope", forbidden: "UnsupportedEnvelope" };
let index = `${bannerComment}\nimport type { EnvelopeMetadata } from "./EnvelopeMetadata.ts";\n`;
for (const [, name] of [...components, ...completenessNames]) index += `import type { ${name} } from "./${name}.ts";\n`;
const unionTypes = [];
for (const [mode, statuses] of statusesByMode) {
  const completeness = statuses.map((status) => nameOfStatus[status]).join(" | ");
  if (mode === "forbidden") {
    index += `export type ${unionNames[mode]} = EnvelopeMetadata & { component: ${components.map(([id]) => JSON.stringify(id)).join(" | ")}; completeness: ${completeness}; data?: never };\n`;
  } else {
    index += `export type ${unionNames[mode]} =\n` + components.map(([id, name]) => `  | (EnvelopeMetadata & { component: ${JSON.stringify(id)}; completeness: ${completeness}; data${mode === "optional" ? "?" : ""}: ${name} })`).join("\n") + ";\n";
  }
  unionTypes.push(unionNames[mode]);
}
index += `export type Envelope = ${unionTypes.join(" | ")};\n`;
outputs.set("index.ts", index);
if (process.argv.includes("--check")) {
  let stale = false;
  for (const [name, content] of outputs) {
    const actual = await readFile(join(outputDir, name), "utf8").catch(() => null);
    if (actual !== content) { console.error(`STALE_TYPES ${name}`); stale = true; }
  }
  if (stale) process.exitCode = 1;
} else {
  await mkdir(outputDir, { recursive: true });
  for (const [name, content] of outputs) await writeFile(join(outputDir, name), content);
}
