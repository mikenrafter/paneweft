// Build tooling only (v1). Generates src/generated/v1/<Name>.ts from the self-contained v1 schemas with
// json-schema-to-typescript (same pin as scripts/gen-types.mjs). Each source schema uses local #/$defs references only,
// so recursion (the tagged Value) stays a named type. `--check` exits 1 with STALE_TYPES <file> when a committed file differs.
import { compile } from "json-schema-to-typescript";
import { readFile, readdir, mkdir, writeFile } from "node:fs/promises";
import { resolve, join } from "node:path";
import { fileURLToPath } from "node:url";

const root = resolve(fileURLToPath(new URL("..", import.meta.url)));
const arg = (name, fallback) => { const at = process.argv.indexOf(name); return at < 0 ? fallback : resolve(process.argv[at + 1]); };
const schemaDir = arg("--schemas", join(root, "src/schemas/v1"));
const outputDir = arg("--out", join(root, "src/generated/v1"));
const GENERATED = { "object-graph": "ObjectGraph", "test-run": "TestRun", job: "Job", adapter: "Adapter", catalogue: "Catalogue", inventory: "Inventory", trail: "Trail", benchmark: "Benchmark" };
const banner = "/* Generated by npm run gen:types:v1 using json-schema-to-typescript 16.0.0. Do not edit. */";
const outputs = new Map();
for (const [file, name] of Object.entries(GENERATED)) {
  const schema = JSON.parse(await readFile(join(schemaDir, `${file}.schema.json`), "utf8"));
  schema.title = name;
  const text = await compile(schema, name, { bannerComment: banner, additionalProperties: false, unknownAny: true, $refOptions: { resolve: { external: false, http: false, file: false } } });
  outputs.set(`${name}.ts`, text);
}
if (process.argv.includes("--check")) {
  let stale = false;
  for (const [name, content] of outputs) {
    let current = null;
    try { current = await readFile(join(outputDir, name), "utf8"); } catch { /* missing */ }
    if (current !== content) { console.error(`STALE_TYPES ${name}`); stale = true; }
  }
  process.exit(stale ? 1 : 0);
}
await mkdir(outputDir, { recursive: true });
for (const [name, content] of outputs) await writeFile(join(outputDir, name), content);
